#!/usr/bin/env node
/* eslint-disable no-console */
"use strict";

/**
 * AI-EVAL review packet renderer (Stream B, B1).
 *
 * Renders the three role review packets (PIM SME, QA, Security) and the approval-status matrix from the Golden Catalog.
 * The catalog is the source of truth; the packets are derived. This script only READS the catalog and WRITES markdown. It does not
 * change any case, any approval, or any status, and it never prints the value of a blocked payload field (field paths only).
 *
 *   node scripts/render-ai-eval-review-packets.cjs           write the four documents
 *   node scripts/render-ai-eval-review-packets.cjs --check   fail if the committed documents differ from a fresh render
 *   --only sme,qa,security,matrix                            restrict write/check to those documents
 */
const { createHash } = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const REPO_ROOT = path.resolve(__dirname, "..");
const CATALOG_PATH = path.join(REPO_ROOT, "test-fixtures", "ai-eval", "golden-catalog.v2.json");
const DOCS_DIR = path.join(REPO_ROOT, "docs", "qa");
const RENDER_DATE = "2026-10-07";
const OUT = {
  sme: "ai-eval-review-packet-pim-sme-2026-10-07.md",
  qa: "ai-eval-review-packet-qa-2026-10-07.md",
  security: "ai-eval-review-packet-security-2026-10-07.md",
  matrix: "ai-eval-approval-status-matrix-2026-10-07.md",
};

function stableStringify(value) {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return `[${value.map((entry) => stableStringify(entry)).join(",")}]`;
  }
  return `{${Object.keys(value)
    .sort()
    .filter((key) => value[key] !== undefined)
    .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`)
    .join(",")}}`;
}

/** Same definition as catalogContentHash in apps/api/test/ai-eval/evaluation.runner.ts (approval metadata excluded). */
function catalogContentHash(catalog) {
  const { approvalPolicy: _policy, ...rest } = catalog;
  const cases = catalog.cases.map((testCase) => {
    const { approvalStatus: _status, approvals: _approvals, ...content } = testCase;
    return content;
  });
  return `sha256:${createHash("sha256").update(stableStringify({ ...rest, cases })).digest("hex")}`;
}

const json = (value) => JSON.stringify(value);
const CATEGORY_ORDER = [
  "clean_extraction",
  "messy_supplier_text",
  "units_specs",
  "ambiguity",
  "contradiction",
  "invalid_data",
  "missing_data",
  "security_adversarial",
];

function requiredApprovers(catalog, testCase) {
  const policy = catalog.approvalPolicy.requiredApprovers;
  return policy[testCase.category] ?? policy.default;
}

function ordered(catalog) {
  return [...catalog.cases].sort(
    (a, b) => CATEGORY_ORDER.indexOf(a.category) - CATEGORY_ORDER.indexOf(b.category) || a.caseId.localeCompare(b.caseId),
  );
}

function isSecurityRelevant(testCase) {
  return testCase.category === "security_adversarial" || (testCase.securityTags ?? []).length > 0;
}

function header(catalog, hash, title, role, intro) {
  return [
    `# ${title}`,
    "",
    `Date: ${RENDER_DATE}`,
    `Catalog: \`${catalog.catalogId}\` version ${catalog.version}, ${catalog.cases.length} cases`,
    `Catalog content hash: \`${hash}\``,
    `Reviewer role: **${role}**`,
    "",
    "**Status: proposal / awaiting human review.** Generated by `scripts/render-ai-eval-review-packets.cjs` from `test-fixtures/ai-eval/golden-catalog.v2.json`. If the catalog changes, regenerate; the catalog is the source of truth.",
    "",
    "**No case in this packet is approved.** Every case stays `DRAFT` until the required humans record their approval in a pull request, in their own name. No agent, script or other reviewer may record an approval on your behalf. A reviewer who corrects case content changes the content hash; the FAST baseline is then re-recorded in the same PR (see the approval packet of 2026-10-05).",
    "",
    intro,
    "",
  ];
}

function inputBlock(testCase) {
  const input = testCase.input;
  const lines = [`- Title: ${json(input.title)}`, `- Description: ${json(input.description)}`, `- Brand: ${json(input.brand)}`, `- Category path: ${json(input.categoryPath)}`];
  lines.push(`- Attributes: ${json(input.attributes ?? {})}`);
  if (input.variants !== undefined) {
    lines.push(`- Variants: ${json(input.variants)}`);
  }
  return lines;
}

function factText(fact) {
  return `${fact.field} = ${json(fact.value)} (from ${fact.source})`;
}

function smePacket(catalog, hash) {
  const out = header(
    catalog,
    hash,
    "Golden Catalog v2: PIM SME review packet",
    "PIM SME",
    [
      "You are asked one question per case: **is this the product knowledge a careful cataloguer would expect?** Required facts must be exactly what the source supports; allowed alternatives must be truly equivalent; fields that must remain unknown must be genuinely absent or conflicting; prohibited claims must be things a model should never invent for this input.",
      "",
      "Price and media references are omitted below because they are not extraction sources. Everything is synthetic: no real customer, supplier, credential or personal datum.",
      "",
      "Decision key: `APPROVE` (correct as written), `CORRECT` (approvable once the noted change is made), `REJECT` (the case should not be authoritative).",
    ].join("\n"),
  );
  let currentCategory = "";
  for (const testCase of ordered(catalog)) {
    if (testCase.category !== currentCategory) {
      currentCategory = testCase.category;
      const count = catalog.cases.filter((c) => c.category === currentCategory).length;
      out.push(`## ${currentCategory} (${count})`, "");
    }
    const e = testCase.expected;
    out.push(
      `### ${testCase.caseId}: ${testCase.scenario}`,
      `- Capability: \`${testCase.capability}\` | criticality: \`${testCase.scoring.criticality}\` | expected outcome: \`${testCase.scoring.expectedPipelineOutcome}\``,
      ...inputBlock(testCase),
      `- Expected facts: ${e.requiredFacts.length ? e.requiredFacts.map(factText).join("; ") : "none"}`,
      `- Allowed alternatives: ${e.allowedAlternatives.length ? e.allowedAlternatives.map((a) => `${a.field} may be ${a.acceptedValues.map(json).join(" or ")} (${a.basis})`).join("; ") : "none"}`,
      `- Allowed inferences: ${e.allowedInferences.length ? e.allowedInferences.map((i) => `${i.field} = ${json(i.value)} (basis: ${i.basis})`).join("; ") : "none"}`,
      `- Ambiguous / must remain unknown: ${e.mustRemainUnknown.length ? e.mustRemainUnknown.join(", ") : "none"}`,
      `- Prohibited unsupported claims: ${e.prohibitedOutputs.length ? e.prohibitedOutputs.map(json).join(", ") : "none"}`,
      "- Reviewer decision: [ ] APPROVE  [ ] CORRECT  [ ] REJECT",
      "- Notes: ____________________",
      "- Reviewer id / date: ____________________",
      "",
    );
  }
  return out.join("\n");
}

function sourceHasValue(testCase, fact) {
  const source = testCase.input[fact.source.split(".")[0]];
  const hay = stableStringify(source ?? "").toLowerCase();
  return hay.includes(String(fact.value).toLowerCase());
}

function qaPacket(catalog, hash) {
  const out = header(
    catalog,
    hash,
    "Golden Catalog v2: QA / AI Evaluation review packet",
    "QA / AI Evaluation",
    [
      "You are asked one question per case: **is this a good test?** It must be unambiguous, reproducible, fair to a correct answer that is worded differently, and in the right category. Where the case is a defence case (blocked payload, injection), the expected outcome must be the only acceptable one.",
      "",
      "\"Auto-check\" lines are computed by the renderer from the catalog and are a convenience, not a verdict: they cannot judge whether a fact is the *right* fact. Decision key: `APPROVE`, `CORRECT`, `REJECT`.",
    ].join("\n"),
  );
  let currentCategory = "";
  for (const testCase of ordered(catalog)) {
    if (testCase.category !== currentCategory) {
      currentCategory = testCase.category;
      const count = catalog.cases.filter((c) => c.category === currentCategory).length;
      out.push(`## ${currentCategory} (${count})`, "");
    }
    const e = testCase.expected;
    const missingFromSource = e.requiredFacts.filter((f) => !sourceHasValue(testCase, f));
    const provenanceFields = new Set(testCase.provenanceExpectations.map((p) => p.field));
    const withoutProvenance = e.requiredFacts.filter((f) => !provenanceFields.has(f.field));
    const overlap = e.prohibitedOutputs.filter((p) => e.requiredFacts.some((f) => String(f.value).toLowerCase() === p.toLowerCase()));
    out.push(
      `### ${testCase.caseId}: ${testCase.scenario}`,
      `- Category: \`${testCase.category}\` | origin: \`${testCase.origin}\` | weight: ${testCase.scoring.caseWeight} | criticality: \`${testCase.scoring.criticality}\``,
      `- Deterministic expectations: ${e.requiredFacts.length} required fact(s), ${testCase.provenanceExpectations.length} provenance expectation(s), expected pipeline outcome \`${testCase.scoring.expectedPipelineOutcome}\`${testCase.payloadExtras ? `, blocked payload fields: ${Object.entries(testCase.payloadExtras).map(([k, v]) => Object.keys(v).map((f) => `\`${k}.${f}\``).join(", ")).join(", ")}` : ""}`,
      `- Alternative-valid outputs: ${e.allowedAlternatives.length ? e.allowedAlternatives.map((a) => `${a.field}: ${a.acceptedValues.map(json).join(" | ")}`).join("; ") : "none (exact match required)"}; allowed inferences: ${e.allowedInferences.length}`,
      `- Ambiguity surface: ${e.mustRemainUnknown.length} field(s) must remain unknown${e.mustRemainUnknown.length ? ` (${e.mustRemainUnknown.join(", ")})` : ""}; ${e.prohibitedOutputs.length} prohibited output(s)`,
      `- Quality signals: ${e.qualitySignals.length ? e.qualitySignals.join(", ") : "none"}`,
      `- Auto-check: required-fact values found in their cited source field: ${missingFromSource.length === 0 ? "all" : `NOT FOUND for ${missingFromSource.map((f) => f.field).join(", ")}`}; every required fact has a provenance expectation: ${withoutProvenance.length === 0 ? "yes" : `NO for ${withoutProvenance.map((f) => f.field).join(", ")}`}; prohibited output equal to a required fact: ${overlap.length === 0 ? "none" : overlap.join(", ")}`,
      "- Reviewer checks: [ ] reproducible  [ ] unambiguous  [ ] alternatives fair  [ ] scoring weight/criticality fair  [ ] fixture realistic and synthetic",
      "- Decision: [ ] APPROVE  [ ] CORRECT  [ ] REJECT",
      "- Notes: ____________________",
      "- Reviewer id / date: ____________________",
      "",
    );
  }
  return out.join("\n");
}

const CONCERNS = [
  ["prompt_injection", "Prompt injection (instructions inside supplier text)", ["prompt_injection", "instruction_in_data"]],
  ["secret_leakage", "Secret leakage / exfiltration", ["secret_exfiltration"]],
  ["credential_shaped_text", "Credential-shaped text (guard precision)", ["guard_false_positive_probe"]],
  ["policy_bypass", "Policy bypass / authority-field override", ["authority_field_override"]],
  ["blocked_data", "Blocked data in the payload (PII, payment, auth, connector)", ["pii"]],
  ["unsafe_completion", "Unsafe completion (unsupported claims)", ["unsupported_claim"]],
];

function securityPacket(catalog, hash) {
  const relevant = ordered(catalog).filter(isSecurityRelevant);
  const out = header(
    catalog,
    hash,
    "Golden Catalog v2: Security review packet",
    "Security",
    [
      `This packet covers the ${relevant.length} security-relevant cases: the ${catalog.cases.filter((c) => c.category === "security_adversarial").length} \`security_adversarial\` cases, which the approval policy requires Security to approve, and ${relevant.length - catalog.cases.filter((c) => c.category === "security_adversarial").length} further cases that carry security tags (\`guard_false_positive_probe\`: ordinary products whose names contain credential-like words, which the credential detector must **not** reject). The policy does not currently require Security approval for those three; Security may ask for it.`,
      "",
      "You are asked, per case: **does it test what it claims, with an unambiguous prohibited outcome?** Blocked payload data is not stored in the catalog as text a reader could misuse: the four `payload_blocked` cases carry only the field paths below, and this packet prints paths, never values. Decision key: `APPROVE`, `CORRECT`, `REJECT`.",
    ].join("\n"),
  );
  out.push("## Concerns each case exercises", "");
  for (const testCase of relevant) {
    const tags = testCase.securityTags ?? [];
    const applicable = CONCERNS.filter(([, , t]) => t.some((tag) => tags.includes(tag))).map(([, label]) => label);
    if (testCase.payloadExtras && !applicable.includes(CONCERNS[4][1])) {
      applicable.push(CONCERNS[4][1]);
    }
    out.push(`- ${testCase.caseId}: ${applicable.length ? applicable.join("; ") : "none mapped"}`);
  }
  out.push("", "## Coverage observations for the reviewer", "", "Computed from the case tags. These are observations, not an assessment of adequacy.", "");
  for (const [, label, tagList] of CONCERNS) {
    const ids = relevant.filter((c) => (c.securityTags ?? []).some((t) => tagList.includes(t)) || (label === CONCERNS[4][1] && c.payloadExtras)).map((c) => c.caseId);
    out.push(`- ${label}: ${ids.length} case(s)${ids.length ? ` (${ids.join(", ")})` : ""}`);
  }
  out.push(
    "- Credential-shaped free text that the detector must REJECT is not exercised by any catalog case: the three probes above test the opposite (no false rejection). Positive detection is covered by the AI-POL-003 vectors, outside the catalog; Security may want a catalog case so FULL evaluation measures it too.",
    "- Not represented by any case: tenant leakage across tenants, provider-side retention or logging behaviour, output channels other than the structured suggestion (for example the notes field in a rendered UI). Those belong to other gates; they are listed so their absence is a decision, not an oversight.",
    "",
    "## Cases",
    "",
  );
  for (const testCase of relevant) {
    const e = testCase.expected;
    const extras = testCase.payloadExtras ? Object.entries(testCase.payloadExtras).flatMap(([k, v]) => Object.keys(v).map((f) => `${k}.${f}`)) : [];
    out.push(
      `### ${testCase.caseId}: ${testCase.scenario}`,
      `- Category: \`${testCase.category}\` | security tags: ${(testCase.securityTags ?? []).map((t) => `\`${t}\``).join(", ") || "none"} | criticality: \`${testCase.scoring.criticality}\``,
      `- Expected pipeline outcome: \`${testCase.scoring.expectedPipelineOutcome}\``,
      `- Blocked payload field paths (values not shown): ${extras.length ? extras.map((p) => `\`${p}\``).join(", ") : "none"}`,
      `- Description as supplied: ${json(testCase.input.description)}`,
      ...(testCase.input.attributes && Object.keys(testCase.input.attributes).length ? [`- Attributes as supplied: ${json(testCase.input.attributes)}`] : []),
      `- Prohibited outputs: ${e.prohibitedOutputs.length ? e.prohibitedOutputs.map(json).join(", ") : "none (the pipeline must block before any model call)"}`,
      `- Required facts that must still be extracted despite the attack: ${e.requiredFacts.length ? e.requiredFacts.map((f) => f.field).join(", ") : "none"}`,
      "- Reviewer checks: [ ] tests what it claims  [ ] prohibited outcome unambiguous  [ ] no real secret or personal data  [ ] expected outcome is the only safe one",
      "- Concern notes (injection / secret leakage / credential-shaped / policy bypass / provenance / prohibited fields / unsafe completion): ____________________",
      "- Decision: [ ] APPROVE  [ ] CORRECT  [ ] REJECT",
      "- Reviewer id / date: ____________________",
      "",
    );
  }
  return out.join("\n");
}

const ROLE_LABEL = { pimSme: "PIM SME", qa: "QA", security: "Security" };

function cell(testCase, required, role) {
  if (!required.includes(role)) {
    return "n/a";
  }
  const approval = testCase.approvals?.[role];
  return approval ? `APPROVED (${approval.by}, ${approval.date})` : "PENDING";
}

function matrixDoc(catalog, hash) {
  const cases = ordered(catalog);
  const rows = cases.map((testCase) => {
    const required = requiredApprovers(catalog, testCase);
    const cells = ["pimSme", "qa", "security"].map((role) => cell(testCase, required, role));
    const complete = required.every((role) => testCase.approvals?.[role]) && testCase.approvalStatus === "APPROVED";
    return { testCase, required, cells, complete };
  });
  const approved = rows.filter((r) => r.complete).length;
  const out = header(
    catalog,
    hash,
    "Golden Catalog v2: approval status matrix",
    "All (read-only status)",
    "Derived from the `approvalStatus` and `approvals` fields in the catalog. A case counts as authoritative only when its status is `APPROVED` **and** every required approver is recorded. Required approvers: PIM SME and QA for every case; Security additionally for `security_adversarial`.",
  );
  out.push("## Overall authority", "");
  out.push(`- Authoritative cases: **${approved} of ${catalog.cases.length}**`);
  out.push(`- Cases in status \`DRAFT\`: ${catalog.cases.filter((c) => c.approvalStatus === "DRAFT").length}`);
  out.push(
    approved === catalog.cases.length
      ? "- FULL evaluation scope: all cases may be authoritative."
      : "- FULL evaluation: **non-authoritative** for every case that is not approved. Model numbers on `DRAFT` cases are informational only and cannot support Gate B or a live-provider decision.",
  );
  out.push("", "## By category", "", "| Category | Cases | Approved | Pending |", "|---|---|---|---|");
  for (const category of CATEGORY_ORDER) {
    const inCat = rows.filter((r) => r.testCase.category === category);
    const done = inCat.filter((r) => r.complete).length;
    out.push(`| ${category} | ${inCat.length} | ${done} | ${inCat.length - done} |`);
  }
  out.push("", "## By role", "", "| Role | Approvals recorded | Approvals required |", "|---|---|---|");
  for (const role of ["pimSme", "qa", "security"]) {
    const needed = rows.filter((r) => r.required.includes(role));
    const have = needed.filter((r) => r.testCase.approvals?.[role]).length;
    out.push(`| ${ROLE_LABEL[role]} | ${have} | ${needed.length} |`);
  }
  out.push("", "## Per case", "", "| Case | Category | Status | PIM SME | QA | Security | Authoritative |", "|---|---|---|---|---|---|---|");
  for (const row of rows) {
    out.push(`| ${row.testCase.caseId} | ${row.testCase.category} | ${row.testCase.approvalStatus} | ${row.cells.join(" | ")} | ${row.complete ? "yes" : "no"} |`);
  }
  out.push("", "## Review order (suggested, unchanged from the 2026-10-05 packet)", "", "1. clean_extraction, then messy_supplier_text, units_specs; 2. ambiguity, contradiction, invalid_data, missing_data; 3. security_adversarial in parallel with Security as owner.", "");
  return out.join("\n");
}

function renderAll() {
  const catalog = JSON.parse(fs.readFileSync(CATALOG_PATH, "utf8"));
  const hash = catalogContentHash(catalog);
  return {
    hash,
    files: {
      [OUT.sme]: smePacket(catalog, hash),
      [OUT.qa]: qaPacket(catalog, hash),
      [OUT.security]: securityPacket(catalog, hash),
      [OUT.matrix]: matrixDoc(catalog, hash),
    },
  };
}

function main() {
  const { hash, files } = renderAll();
  const check = process.argv.includes("--check");
  const onlyArg = process.argv.indexOf("--only");
  const only = onlyArg >= 0 ? String(process.argv[onlyArg + 1] ?? "").split(",").map((k) => OUT[k.trim()]).filter(Boolean) : null;
  let drift = 0;
  for (const [name, content] of Object.entries(files)) {
    if (only && !only.includes(name)) {
      continue;
    }
    const target = path.join(DOCS_DIR, name);
    const text = `${content.trimEnd()}\n`;
    if (check) {
      const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
      if (current !== text) {
        console.error(`DRIFT: ${name} differs from a fresh render`);
        drift += 1;
      }
    } else {
      fs.writeFileSync(target, text, "utf8");
      console.log(`wrote docs/qa/${name} (${text.split("\n").length - 1} lines)`);
    }
  }
  console.log(`catalog content hash ${hash}`);
  if (drift > 0) {
    process.exit(1);
  }
}

if (require.main === module) {
  main();
}

module.exports = { catalogContentHash, renderAll };
